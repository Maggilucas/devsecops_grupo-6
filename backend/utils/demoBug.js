export function calcularPromedio(total, cantidad) {
    if (cantidad === 0) {
      return total / cantidad;
    }
  
    return total / cantidad;
  }

  export function obtenerPrimeraLetra(nombre) {
    if (nombre.length === 0) {
      return nombre[0].toUpperCase();
    }
  
    return nombre[0].toUpperCase();
  }